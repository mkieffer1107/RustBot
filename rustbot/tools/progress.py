#!/usr/bin/env python3
"""Report source translation and WASM integration presence, not behavior or parity."""
import argparse
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
HEADER = re.compile(r'^\s*//\s*@generated by py2rs from (bot/[^\s]+\.py)\s*$', re.M)
SPAN = re.compile(r'^\s*//\s*py:\s*(bot/[^\s]+\.py):(\d+)-(\d+)\s+(.+?)\s*$', re.M)
FUNCTION = re.compile(r'^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?(?:unsafe\s+)?fn\s+\w+', re.M)
# A header, a declaration and real code are required; use statements alone are scaffolding.
DECLARATION = re.compile(r'^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+|unsafe\s+)?(?:fn|struct|enum|impl|const|static|type|mod)\s+\w+', re.M)
PLACEHOLDER = re.compile(r'\b(?:todo!|unimplemented!|compile_error!)\s*\(')


def rust_path(source, bot_dir, rust_dir):
    rel = source.relative_to(bot_dir)
    if rel.name == '__init__.py':
        return rust_dir / rel.parent / ('lib.rs' if rel.parent == Path('.') else 'mod.rs')
    return (rust_dir / rel).with_suffix('.rs')


def report(root):
    bot = root / 'reference/pybot/bot'
    rust = root / 'rustbot/crates/bot/src'
    if not bot.is_dir():
        raise FileNotFoundError(f'source directory missing: {bot}')
    sources = sorted(p for p in bot.rglob('*.py') if p.name != '__main__.py')
    files = []
    source_functions = 0
    translated_functions = 0
    translated_spans = 0
    for source in sources:
        source_rel = source.relative_to(bot.parent).as_posix()
        tree = ast.parse(source.read_bytes(), filename=source_rel)
        source_count = sum(isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) for n in ast.walk(tree))
        source_functions += source_count
        target = rust_path(source, bot, rust)
        if not target.is_file():
            continue
        code = target.read_text()
        header = HEADER.search(code)
        if not header or header.group(1) != source_rel or not DECLARATION.search(code) or PLACEHOLDER.search(code):
            continue
        spans = [m for m in SPAN.finditer(code) if m.group(1) == source_rel]
        functions = len(FUNCTION.findall(code))
        translated_functions += functions
        translated_spans += len(spans)
        files.append({'source': source_rel, 'rust': target.relative_to(root).as_posix(),
                      'source_functions': source_count, 'rust_functions': functions, 'source_spans': len(spans)})
    wasm = root / 'wasmbot'
    return {
        'definition': 'Generated header matches source, a Rust declaration is present, and no todo!, unimplemented!, or compile_error! placeholder occurs. Counts indicate presence, not correctness or parity.',
        'native': {'expected_source_files': len(sources), 'translated_source_files': len(files),
                   'source_functions': source_functions, 'rust_functions_in_translated_files': translated_functions,
                   'source_spans_in_translated_files': translated_spans, 'translated_files': files},
        'wasm': {'shared_core': 'rustbot/crates/bot', 'unique_translated_source_files': len(files),
                 'cargo_manifest_present': (wasm / 'Cargo.toml').is_file(),
                 'web_worker_present': (wasm / 'web/worker.js').is_file(),
                 'web_index_present': (wasm / 'web/index.html').is_file(),
                 'node_replay_present': (wasm / 'node/replay.mjs').is_file()},
        'combined': {'expected_unique_source_files': len(sources),
                     'translated_unique_source_files': len(files),
                     'note': 'Native and WASM share each bot translation; it is counted once.'},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    print(json.dumps(report(args.root.resolve()), indent=2))


if __name__ == '__main__':
    main()
