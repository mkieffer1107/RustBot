#!/usr/bin/env python3
"""Generate normalization tables from CPython 3.14's Unicode 16.0.0 database."""

from pathlib import Path
import shutil
import subprocess
import sys
import unicodedata

if sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
    raise SystemExit("Requires CPython 3.14 with Unicode database 16.0.0")
rustfmt = shutil.which("rustfmt")
if rustfmt is None:
    raise SystemExit("rustfmt is required to generate deterministic formatted output")

OUTPUT = Path(__file__).resolve().parents[1] / "crates/pyrt/src/unicode_normalization_data.rs"


def main():
    decomposition = []
    composition = []
    combining = []
    start = None
    previous = 0
    for codepoint in range(0x110000):
        char = chr(codepoint)
        combining_class = unicodedata.combining(char)
        if combining_class != previous:
            if previous:
                combining.append((start, codepoint - 1, previous))
            start, previous = codepoint, combining_class
        if 0xAC00 <= codepoint < 0xD7A4:
            continue  # Hangul syllables are handled by the runtime algorithm.
        mapping = unicodedata.decomposition(char).split()
        if not mapping:
            continue
        compatibility = mapping[0].startswith("<")
        if compatibility:
            mapping = mapping[1:]
        points = tuple(int(part, 16) for part in mapping)
        decomposition.append((codepoint, compatibility, points))
        if not compatibility and len(points) == 2:
            pair = "".join(chr(point) for point in points)
            # This oracle test incorporates the full composition exclusions,
            # including nonstarter decompositions and post-version additions.
            if unicodedata.normalize("NFC", pair) == char:
                composition.append((*points, codepoint))
    if previous:
        combining.append((start, 0x10FFFF, previous))
    composition.sort()
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as output:
        output.write("// @generated by tools/generate_normalization.py using CPython 3.14, Unicode 16.0.0.\n")
        output.write("// Hangul syllables are decomposed/composed algorithmically in unicode.rs.\n")
        output.write("pub(crate) static DECOMPOSITION: &[(u32, bool, &[u32])] = &[\n")
        for codepoint, compatibility, points in decomposition:
            output.write(f"(0x{codepoint:x}, {str(compatibility).lower()}, &[")
            output.write(",".join(f"0x{point:x}" for point in points))
            output.write("]),\n")
        output.write("];\npub(crate) static COMPOSITION: &[(u32, u32, u32)] = &[\n")
        for first, second, codepoint in composition:
            output.write(f"(0x{first:x},0x{second:x},0x{codepoint:x}),\n")
        output.write("];\npub(crate) static COMBINING: &[(u32, u32, u8)] = &[\n")
        for first, last, value in combining:
            output.write(f"(0x{first:x},0x{last:x},{value}),\n")
        output.write("];\n")
    subprocess.run([rustfmt, "--edition", "2024", str(OUTPUT)], check=True)
    print(f"Unicode 16.0.0: {len(decomposition)} decompositions, "
          f"{len(composition)} compositions, {len(combining)} combining ranges")


if __name__ == "__main__":
    main()
