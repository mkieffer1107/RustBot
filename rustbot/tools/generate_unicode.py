#!/usr/bin/env python3
"""Generate Rust Unicode tables from CPython 3.14's pinned Unicode database."""

import shutil
import subprocess
import sys
import unicodedata
from pathlib import Path

if sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
    raise SystemExit("Requires CPython 3.14 with Unicode database 16.0.0")
rustfmt = shutil.which("rustfmt")
if rustfmt is None:
    raise SystemExit("rustfmt is required to generate deterministic formatted output")

out = Path(__file__).resolve().parents[1] / "crates/pyrt/src/unicode_data.rs"
properties = [
    "isalpha", "isdigit", "isdecimal", "isnumeric", "isalnum", "isspace",
    "isupper", "islower", "istitle", "isprintable", "isidentifier",
]


def flags(c):
    result = sum(1 << i for i, name in enumerate(properties) if getattr(c, name)())
    if ("A" + c).isidentifier():
        result |= 1 << 11
    cased = c.islower() or c.isupper() or c.istitle()
    if cased:
        result |= 1 << 12
    # Contextual sigma probes distinguish Case_Ignorable even when it overlaps
    # Cased: the preceding sigma remains final when followed only by c.
    ignorable = (("AΣ" + c).lower()[1] == "ς" if cased
                 else ("A" + c + "Σ").lower().endswith("ς"))
    if ignorable:
        result |= 1 << 13
    return result


ranges = []
start = 0
previous = None
maps = {name: [] for name in ("lower", "upper", "title", "casefold")}
for codepoint in range(0x110000):
    char = chr(codepoint)
    value = flags(char)
    if value != previous:
        if previous is not None:
            ranges.append((start, codepoint - 1, previous))
        start, previous = codepoint, value
    if not 0xD800 <= codepoint <= 0xDFFF:
        for name, entries in maps.items():
            mapped = getattr(char, name)()
            if mapped != char:
                entries.append((codepoint, mapped))
ranges.append((start, 0x10FFFF, previous))


def literal(s):
    return '"' + "".join("\\u{%x}" % ord(char) for char in s) + '"'


with out.open("w", encoding="utf-8", newline="\n") as f:
    f.write("// @generated by tools/generate_unicode.py using CPython 3.14, Unicode 16.0.0.\n")
    f.write("static PROPERTIES: &[(u32,u32,u16)] = &[\n")
    for first, last, value in ranges:
        if value:
            f.write(f"({first},{last},{value}),\n")
    f.write("];\npub(crate) fn property(c: char, bit: u16) -> bool { let n=c as u32; let i=PROPERTIES.partition_point(|x| x.1<n); PROPERTIES.get(i).is_some_and(|x| x.0<=n && x.2 & bit != 0) }\n")
    for name, entries in maps.items():
        upper = name.upper()
        f.write(f"static {upper}: &[(u32,&str)] = &[\n")
        for codepoint, mapped in entries:
            f.write(f"({codepoint},{literal(mapped)}),\n")
        f.write("];\n")
        f.write(f"pub(crate) fn {name}(c: char) -> Option<&'static str> {{ {upper}.binary_search_by_key(&(c as u32), |x| x.0).ok().map(|i| {upper}[i].1) }}\n")

    # Python regex categories use alphanumeric, decimal and whitespace, whose
    # membership differs from the categories supplied by Rust's regex crate.
    categories = [
        ("WORD", lambda c: c == "_" or c.isalnum()),
        ("DIGIT", str.isdecimal),
        ("SPACE", str.isspace),
    ]
    for name, predicate in categories:
        pieces = []
        start = None
        for codepoint in range(0x110001):
            inside = (codepoint < 0x110000 and not 0xD800 <= codepoint <= 0xDFFF
                      and predicate(chr(codepoint)))
            if inside and start is None:
                start = codepoint
            if not inside and start is not None:
                end = codepoint - 1
                pieces.append("\\x{%x}" % start + ("-\\x{%x}" % end if end != start else ""))
                start = None
        f.write(f'pub(crate) const REGEX_{name}: &str = r"{"".join(pieces)}";\n')

subprocess.run([rustfmt, "--edition", "2024", str(out)], check=True)
