import importlib.util
from pathlib import Path
import tempfile
import unittest

SPEC = importlib.util.spec_from_file_location('progress', Path(__file__).resolve().parents[1] / 'progress.py')
progress = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(progress)


class ProgressTests(unittest.TestCase):
    def test_translation_and_wasm_presence(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            bot = root / 'reference/pybot/bot'
            src = root / 'rustbot/crates/bot/src'
            (bot / 'pkg').mkdir(parents=True)
            (src / 'pkg').mkdir(parents=True)
            (bot / '__init__.py').write_text('def a(): pass\n')
            (bot / '__main__.py').write_text('def cli(): pass\n')
            (bot / 'pkg' / '__init__.py').write_text('')
            (bot / 'pkg' / 'leaf.py').write_text('def foo(): pass\n')
            (src / 'lib.rs').write_text('//! Bootstrap placeholder\n')
            (src / 'pkg' / 'mod.rs').write_text('// @generated by py2rs from bot/pkg/__init__.py\nuse foo::bar;\n')
            (src / 'pkg' / 'leaf.rs').write_text('// @generated by py2rs from bot/pkg/leaf.py\n// py: bot/pkg/leaf.py:1-1 foo\npub fn foo() {}\n')
            (root / 'wasmbot/web').mkdir(parents=True)
            (root / 'wasmbot/web/worker.js').write_text('')
            result = progress.report(root)
            native = result['native']
            self.assertEqual((native['expected_source_files'], native['translated_source_files']), (3, 1))
            self.assertEqual((native['source_functions'], native['rust_functions_in_translated_files'], native['source_spans_in_translated_files']), (2, 1, 1))
            self.assertEqual(native['translated_files'][0]['source'], 'bot/pkg/leaf.py')
            self.assertTrue(result['wasm']['web_worker_present'])
            self.assertFalse(result['wasm']['cargo_manifest_present'])
            self.assertEqual(result['wasm']['unique_translated_source_files'], 1)
            self.assertEqual(result['combined']['translated_unique_source_files'], 1)
            self.assertEqual(result['combined']['expected_unique_source_files'], 3)
            (src / 'pkg' / 'leaf.rs').write_text('// @generated by py2rs from bot/pkg/leaf.py\nfn foo() { todo!() }\n')
            self.assertEqual(progress.report(root)['native']['translated_source_files'], 0)


if __name__ == '__main__':
    unittest.main()
