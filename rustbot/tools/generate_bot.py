#!/usr/bin/env python3
"""Generate native bot mirrors and their registry from selected pinned sources."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

from py2rs.compiler import UnsupportedSyntax, rust_string, translate
from py2rs.__main__ import mirror

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "reference/pybot/bot"
OUTPUT = ROOT / "rustbot/crates/bot/src"
MANIFEST = ROOT / "rustbot/docs/translated.json"


def generate(paths, partial=False, format_output=True):
    selected = {SOURCE / "__init__.py"}
    for path in paths:
        path = (SOURCE / path).resolve()
        if not path.is_relative_to(SOURCE):
            raise ValueError(f"source outside {SOURCE}: {path}")
        if path.is_dir():
            selected.update(path.rglob("*.py"))
        elif path.suffix == ".py" and path.is_file():
            selected.add(path)
        else:
            raise ValueError(f"not a source file or directory: {path}")
    results, failures = {}, []
    for path in sorted(selected):
        relative = path.relative_to(SOURCE)
        if relative == Path("__main__.py"):
            continue
        parts = list(relative.with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        module = ".".join(["bot", *parts])
        try:
            result = translate(path.read_text(encoding="utf-8"), module, f"bot/{relative.as_posix()}")
        except (UnsupportedSyntax, SyntaxError, ValueError) as error:
            failures.append({"source": f"bot/{relative.as_posix()}", "error": str(error)})
            if not partial:
                raise
            continue
        target = mirror(relative)
        if (OUTPUT / target).exists() and "// manual" in (OUTPUT / target).read_text():
            raise ValueError(f"manual override would be overwritten: {target}")
        results[module] = (target, result)
    formatter = shutil.which("rustfmt")
    if format_output and formatter is None:
        raise ValueError("rustfmt is required")
    old = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else []
    metadata = {entry["module"]: entry for entry in old}
    for module, (target, result) in results.items():
        text = result.rust
        if module == "bot":
            text += '\npub mod support;\npub use support::{new_runtime, call};\npub const PORT_STATUS: &str = "native translation is under development";\n'
        path = OUTPUT / target
        path.parent.mkdir(parents=True, exist_ok=True)
        # Unicode separators are valid string data, not generated source lines.
        path.write_text("\n".join(line.rstrip(" \t\r") for line in text.split("\n")).rstrip("\n") + "\n", encoding="utf-8")
        metadata[module] = {"rust_path": target.as_posix(), **result.metadata}
    entries = sorted(metadata.values(), key=lambda item: item["module"])
    lines = ["// @generated by tools/generate_bot.py; registry only.",
             "use pyrt::runtime::{Runtime,ModuleInit};"]
    for index, entry in enumerate(entries):
        if entry["module"] != "bot":
            lines += [f'#[path = {rust_string("../" + entry["rust_path"])}]', f"mod m{index};"]
    lines.append("pub static MODULES: &[(&str, ModuleInit)] = &[")
    for index, entry in enumerate(entries):
        initializer = "crate::INIT" if entry["module"] == "bot" else f"m{index}::{entry['initializer']}"
        lines.append(f"({rust_string(entry['module'])},{initializer}),")
    lines += ["];", "pub fn register(rt: &mut Runtime) { for (name, init) in MODULES { rt.register_module(*name,*init); } }"]
    registry = OUTPUT / "support/generated.rs"
    registry.parent.mkdir(parents=True, exist_ok=True)
    registry.write_text("\n".join(lines) + "\n")
    if format_output:
        subprocess.run([formatter, "--edition", "2024", "--config", "skip_children=true", str(registry)], check=True)
        for target,_ in results.values():
            subprocess.run([formatter,"--edition","2024","--config","skip_children=true",str(OUTPUT/target)],check=True)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(entries, indent=2) + "\n")
    print(json.dumps({"generated": len(results), "registered": len(entries), "unsupported": failures}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("paths", nargs="+", help="paths below reference/pybot/bot")
    parser.add_argument("--partial", action="store_true", help="emit only fully translated files and report unsupported files")
    parser.add_argument("--no-rustfmt", action="store_true", help="emit valid Rust without the optional formatting pass")
    args = parser.parse_args()
    try:
        generate(args.paths, args.partial, not args.no_rustfmt)
    except (UnsupportedSyntax, SyntaxError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
